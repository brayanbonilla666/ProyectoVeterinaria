
package vModelo;

public class Persona {
    
    private String nombre;
    private String cedula;
    private String email;
    private String celular;

    public Persona(String nombre, String cedula, String email, String celular) {
        this.nombre = nombre;
        this.cedula = cedula;
        this.email = email;
        this.celular = celular;
    }
    
    
    
}
