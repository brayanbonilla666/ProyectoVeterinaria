    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed

        String sCedula = txtCedula.getText();
        String sNombre = txtNombre.getText();
        String sApellido = txtApellido.getText();
        String sEdad = txtFNacimiento.getText();
        String sEmail = txtEmail.getText();
        String sNumeroCelular = txtNCelular.getText();
        
        if (sCedula.isEmpty() || sNombre.isEmpty() || sApellido.isEmpty() || sEdad.isEmpty() || sNombre.isEmpty() || sApellido.isEmpty() || sEdad.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor, llene todos los campos comunes", "Campos vacios" ,JOptionPane.WARNING_MESSAGE);
            return;
        } 
        
        javax.swing.table.DefaultTableModel modeloTbl = (javax.swing.table.DefaultTableModel) tblPropietarios.getModel();
        modeloTbl.addRow(new Object[]{sCedula, sNombre, sApellido, sEdad, sEmail, sNumeroCelular});
        
        

    }//GEN-LAST:event_btnRegistrarActionPerformed

