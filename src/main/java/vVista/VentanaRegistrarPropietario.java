    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        
        int filaSeleccionada = tblPropietarios.getSelectedRow();

        if (filaSeleccionada == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Selecciona una fila de la tabla para eliminar.", "Sin selección", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        javax.swing.table.DefaultTableModel modeloTbl = (javax.swing.table.DefaultTableModel) tblPropietarios.getModel();
        modeloTbl.removeRow(filaSeleccionada);
    }//GEN-LAST:event_btnEliminarActionPerformed

